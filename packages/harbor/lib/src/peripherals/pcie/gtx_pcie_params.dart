/// Fixed GTXE2 settings for a PCIe x1 link at 2.5 and 5 GT/s on a 100 MHz
/// reference clock with the CPLL.
///
/// Each value has a source. The sources are chapters of UG476 (7 Series
/// FPGAs GTX/GTH Transceivers), PG054 (7 Series FPGAs Integrated Block
/// for PCI Express), and values that ran on a KC705. The openXC7 flow has defaults that are different from the
/// Xilinx library, so the wrapper must set each parameter. A value with the
/// source [_lib] is the library default, stated so that the flow does not use
/// its own default.
library;

